BEGIN;

CREATE TABLE IF NOT EXISTS public.cuentas_oauth (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id BIGINT NOT NULL,

    proveedor VARCHAR(30) NOT NULL,

    proveedor_usuario_id VARCHAR(255) NOT NULL,

    correo_proveedor VARCHAR(180),

    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT cuentas_oauth_usuario_id_fkey
        FOREIGN KEY (usuario_id)
        REFERENCES public.usuarios(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_oauth_identidad
        UNIQUE (proveedor, proveedor_usuario_id),

    CONSTRAINT uq_oauth_usuario_proveedor
        UNIQUE (usuario_id, proveedor),

    CONSTRAINT ck_oauth_proveedor
        CHECK (proveedor IN ('google'))
);

CREATE INDEX IF NOT EXISTS idx_cuentas_oauth_usuario
ON public.cuentas_oauth(usuario_id);

ALTER TABLE public.cuentas_oauth
ENABLE ROW LEVEL SECURITY;

COMMIT;
