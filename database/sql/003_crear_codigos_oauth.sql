BEGIN;

CREATE TABLE IF NOT EXISTS public.codigos_oauth (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id BIGINT NOT NULL
        REFERENCES public.usuarios(id)
        ON DELETE CASCADE,

    codigo_hash CHAR(64) NOT NULL UNIQUE,

    expira_en TIMESTAMPTZ NOT NULL,

    utilizado_en TIMESTAMPTZ NULL,

    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índice para consultar y limpiar códigos expirados.
CREATE INDEX IF NOT EXISTS idx_codigos_oauth_expiracion
ON public.codigos_oauth(expira_en);

-- Mantener la política de seguridad del proyecto.
ALTER TABLE public.codigos_oauth
ENABLE ROW LEVEL SECURITY;

COMMIT;
